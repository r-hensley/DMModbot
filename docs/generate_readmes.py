"""Build the user and admin READMEs from templates and bot source."""

import ast
from pathlib import Path
from string import Template


ROOT = Path(__file__).resolve().parents[1]
HEADER = "<!-- Generated by docs/generate_readmes.py. Edit the templates in docs/. -->\n\n"


def source(path):
    return ast.parse((ROOT / path).read_text(encoding="utf-8"), filename=path)


def literal(tree, name):
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == name for target in node.targets
        ):
            return ast.literal_eval(node.value)
    raise ValueError(f"Missing source assignment: {name}")


def command_reference():
    prefixes = {"commands.command": "_", "app_commands.command": "/"}
    rows = []
    for path in ("cogs/admin.py", "cogs/submod.py", "cogs/resolve_after.py"):
        for node in ast.walk(source(path)):
            if not isinstance(node, ast.AsyncFunctionDef):
                continue
            for decorator in node.decorator_list:
                if not isinstance(decorator, ast.Call):
                    continue
                prefix = prefixes.get(ast.unparse(decorator.func))
                if prefix is None:
                    continue
                options = {item.arg: ast.literal_eval(item.value) for item in decorator.keywords
                           if item.arg in {"name", "description", "hidden"}}
                if options.get("hidden"):
                    continue
                name = prefix + options.get("name", node.name)
                if prefix == "/":
                    args = node.args.args[2:]  # self, interaction
                    required = len(args) - len(node.args.defaults)
                    for i, arg in enumerate(args):
                        option = f"{arg.arg}:…"
                        name += f" {option}" if i < required else f" [{option}]"
                description = options.get("description") or ast.get_docstring(node) or ""
                summary = description.splitlines()[0].strip() if description else ""
                summary = summary.split(". ", 1)[0].replace("|", "\\|")
                rows.append(f"| `{name}` | {summary} |")
    return "\n".join(sorted(rows, key=str.casefold))


def render(audience, **values):
    template = ROOT / "docs" / f"readme_{audience}.md"
    text = Template(template.read_text(encoding="utf-8")).substitute(values)
    output = ROOT / f"readme_auto_{audience}.md"
    contents = (HEADER + text.rstrip() + "\n").encode("utf-8")
    if not output.exists() or output.read_bytes() != contents:
        output.write_bytes(contents)


def main():
    intake = source("cogs/report_intake.py")
    labels = literal(intake, "COPY")["en"]
    topics = literal(intake, "TOPICS")
    topic_list = []
    routing_rows = []
    for topic, (room, _) in topics.items():
        qualifier = " (where available)" if topic == "voice_access" else ""
        topic_list.append(f"- {labels[topic]}{qualifier}")
        routing_rows.append(f"| {labels[topic]}{qualifier} | {room.capitalize()} |")

    render("user", **labels, topic_list="\n".join(topic_list))
    render("admin", command_rows=command_reference(), routing_rows="\n".join(routing_rows),
           socket_env=literal(source("Modbot.py"), "SOCKET_ENV"),
           meta_post=literal(source("cogs/utils/helper_functions.py"), "FORUM_META_THREAD_NAME"))


if __name__ == "__main__":
    main()
